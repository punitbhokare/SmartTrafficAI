
import os
import pickle
import streamlit as st
import pandas as pd

st.set_page_config(
    page_title="SmartTraffic AI",
    page_icon="🚦",
    layout="wide"
)

# ---------- HEADER ----------
st.title("🚦 SmartTraffic AI")
st.subheader("Intelligent Traffic Congestion Prediction")
st.caption("Machine Learning | Traffic Analytics | Smart Cities")

st.info(
    "Academic prototype using a small synthetic dataset. "
    "It does not use live traffic feeds."
)

# ---------- LOAD MODEL ----------
if not os.path.exists("traffic_model.pkl"):
    st.error(
        "Model file not found. Run: python train_model.py"
    )
    st.stop()

with open("traffic_model.pkl", "rb") as f:
    model = pickle.load(f)

# ---------- SIDEBAR ----------
st.sidebar.header("Traffic Input")

city = st.sidebar.selectbox(
    "Select City",
    ["Nagpur", "Mumbai", "Pune", "Bengaluru"]
)

hour = st.sidebar.slider(
    "Hour of Day",
    0, 23, 18
)

day_type = st.sidebar.selectbox(
    "Day Type",
    ["Weekday", "Weekend"]
)

vehicles = st.sidebar.slider(
    "Estimated Number of Vehicles",
    10, 150, 110
)

predict_clicked = st.sidebar.button(
    "Predict Congestion",
    type="primary",
    use_container_width=True
)

# ---------- TABS ----------
overview_tab, prediction_tab, analytics_tab, about_tab = st.tabs(
    ["🏠 Overview", "🔮 Prediction", "📊 Analytics", "ℹ️ About Project"]
)

# ---------- OVERVIEW ----------
with overview_tab:
    st.header("Traffic Dashboard")

    col1, col2, col3 = st.columns(3)

    col1.metric("Selected City", city)
    col2.metric("Selected Hour", f"{hour:02d}:00")
    col3.metric("Estimated Vehicles", vehicles)

    st.subheader("Estimated Traffic by Hour")

    hours = list(range(6, 23))
    counts = [
        25, 40, 75, 100, 85, 60, 50, 55, 65,
        70, 80, 95, 110, 90, 65, 40, 30
    ]

    traffic_df = pd.DataFrame({
        "Hour": hours,
        "Estimated Vehicles": counts
    })

    st.line_chart(
        traffic_df.set_index("Hour"),
        y="Estimated Vehicles"
    )

    st.caption(
        "Illustrative values for demonstrating chart functionality; "
        "not measured traffic data."
    )

# ---------- PREDICTION ----------
with prediction_tab:
    st.header("Congestion Prediction")

    st.write("Selected city:", city)
    st.write("Selected time:", f"{hour:02d}:00")
    st.write("Day type:", day_type)
    st.write("Estimated vehicles:", vehicles)

    if predict_clicked:
        day_value = 0 if day_type == "Weekday" else 1

        input_df = pd.DataFrame(
            [[hour, day_value, vehicles]],
            columns=["hour", "day_type", "vehicles"]
        )

        result = model.predict(input_df)[0]

        st.session_state["last_prediction"] = result
        st.session_state["last_city"] = city

    if "last_prediction" in st.session_state:
        result = st.session_state["last_prediction"]

        if result == "High":
            st.error("🔴 Predicted Congestion: HIGH")
        elif result == "Medium":
            st.warning("🟡 Predicted Congestion: MEDIUM")
        else:
            st.success("🟢 Predicted Congestion: LOW")

        st.caption(
            "Prediction is generated by the trained model using "
            "synthetic training data. It is not a real-world traffic forecast."
        )
    else:
        st.info(
            "Select the traffic inputs in the sidebar, "
            "then click Predict Congestion."
        )

# ---------- ANALYTICS ----------
with analytics_tab:
    st.header("Traffic Analytics")

    st.subheader("1. Hourly Vehicle Estimates")

    st.bar_chart(
        traffic_df.set_index("Hour"),
        y="Estimated Vehicles"
    )

    st.subheader("2. Example Congestion Distribution")

    congestion_df = pd.DataFrame({
        "Congestion Level": ["Low", "Medium", "High"],
        "Illustrative Count": [12, 9, 11]
    })

    st.bar_chart(
        congestion_df.set_index("Congestion Level"),
        y="Illustrative Count"
    )

    st.subheader("3. Sample Traffic Table")
    st.dataframe(traffic_df, use_container_width=True)

    st.caption(
        "Analytics use illustrative sample values, not live city traffic."
    )

# ---------- ABOUT ----------
with about_tab:
    st.header("About the Project")

    st.write(
        "SmartTraffic AI is an educational prototype that demonstrates "
        "how a Machine Learning classifier can categorize traffic "
        "congestion as Low, Medium, or High."
    )

    st.subheader("Objectives")
    st.markdown(
        "- Demonstrate a Machine Learning workflow.\n"
        "- Predict a congestion category from selected inputs.\n"
        "- Visualize illustrative traffic patterns.\n"
        "- Explore how data-driven tools could support traffic planning."
    )

    st.subheader("Technology Used")
    st.markdown(
        "- Python\n"
        "- Streamlit\n"
        "- Pandas\n"
        "- Scikit-learn\n"
        "- Random Forest Classifier"
    )

    st.subheader("Limitations")
    st.write(
        "The model uses a small synthetic dataset and has not been "
        "validated on real traffic measurements. City selection is "
        "currently a dashboard label, not a city-specific model input. "
        "The charts are illustrative, not live traffic records."
    )

st.divider()
st.caption("SmartTraffic AI | College Project Prototype")
